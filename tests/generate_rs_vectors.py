#!/usr/bin/env python3
"""Optional fixture regeneration using independently installed qrcode==8.2.

Run: PYTHONPATH=references/python python3 tests/generate_rs_vectors.py
No qrcode code is included in the reader library. Generated vectors are fixed.
"""
from pathlib import Path
from importlib.metadata import version
import qrcode.base
import qrcode.util

assert version('qrcode') == '8.2', 'Use pinned qrcode 8.2 reference'
rows = []
for parity in range(7, 31):
    for length in (parity + 1, parity + 17, 128, 255):
        payload = bytes(((i * 37 + parity * 19 + length) & 255)
                        for i in range(length - parity))
        buffer = qrcode.util.BitBuffer()
        for b in payload:
            buffer.put(b, 8)
        encoded = qrcode.util.create_bytes(buffer, [qrcode.base.RSBlock(length, len(payload))])
        rows.append('    {' + str(parity) + ', {' + ','.join(map(str, encoded)) + '}},')
output = ('// Generated by generate_rs_vectors.py with qrcode==8.2.\n'
          '// Independent encoder outputs; regenerate only with the pinned reference.\n'
          'const std::vector<RsVector> rs_vectors = {\n' + '\n'.join(rows) + '\n};\n')
Path(__file__).with_name('rs_vectors.inc').write_text(output)
